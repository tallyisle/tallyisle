import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;

bool _sdkHasOhosTargetPlatform() =>
    TargetPlatform.values.any((platform) => platform.name == 'ohos');

void main() {
  group('HarmonyOS pubspec & workflow isolation guardrails', () {
    test(
      'upstream Flutter toolchain keeps root pubspec.yaml and pubspec.lock 100% pure',
      () {
        final pubspec = File('pubspec.yaml').readAsStringSync();
        final lockfile = File('pubspec.lock').readAsStringSync();
        final ohosLockfile = File('tool/ohos/pubspec_ohos.lock');
        expect(ohosLockfile.existsSync(), isTrue);
        expect(
          ohosLockfile.readAsStringSync(),
          contains('third_party/ohos_packages/'),
        );

        if (_sdkHasOhosTargetPlatform()) {
          expect(pubspec, contains('dependency_overrides:'));
          expect(pubspec, contains('third_party/ohos_packages/'));
          expect(pubspec, contains('ohos: system'));
          expect(lockfile, contains('third_party/ohos_packages/'));
        } else {
          expect(
            pubspec,
            isNot(contains('dependency_overrides:')),
            reason:
                'Root pubspec.yaml must stay free of HarmonyOS overrides on main',
          );
          expect(pubspec, isNot(contains('third_party/ohos_packages/')));
          expect(pubspec, isNot(contains('ohos: system')));
          expect(
            lockfile,
            isNot(contains('third_party/ohos_packages/')),
            reason:
                'Root pubspec.lock must stay free of HarmonyOS overrides on main',
          );
        }
      },
    );

    test(
      'build-ohos.yml targets main + v* tags, mounts overrides before pub get, and appends Release HAP',
      () {
        final workflow = File(
          '.github/workflows/build-ohos.yml',
        ).readAsStringSync();
        expect(workflow, isNot(contains('feat/ohos')));
        expect(
          RegExp(
            r'python3 tool/ohos/apply_ohos_pubspec\.py --apply',
          ).allMatches(workflow).length,
          greaterThanOrEqualTo(2),
        );
        expect(workflow, contains('release-ohos:'));
        expect(workflow, contains("startsWith(github.ref, 'refs/tags/v')"));
        expect(workflow, contains('softprops/action-gh-release@v2'));
        expect(workflow, contains('dist-ohos/TallyIsle-HarmonyOS-*.hap'));
      },
    );

    test(
      'apply_ohos_pubspec.py --apply and --restore are idempotent and byte-exact',
      () async {
        final scriptPath = File(
          'tool/ohos/apply_ohos_pubspec.py',
        ).absolute.path;
        final tempDir = await Directory.systemTemp.createTemp(
          'ohos_pubspec_isolation_',
        );
        addTearDown(() async {
          if (await tempDir.exists()) {
            await tempDir.delete(recursive: true);
          }
        });

        const cleanPubspec = '''name: tallyisle
version: 0.6.0+8
environment:
  sdk: '>=3.12.0 <4.0.0'
dependencies:
  flutter:
    sdk: flutter
''';
        const cleanLock = '''# Generated by pub
packages:
  path_provider:
    dependency: "direct main"
    source: hosted
    version: "2.1.6"
sdks:
  dart: ">=3.13.0 <4.0.0"
''';
        final ohosLock = File('tool/ohos/pubspec_ohos.lock').readAsStringSync();

        await Directory(
          p.join(tempDir.path, 'tool', 'ohos'),
        ).create(recursive: true);
        await File(
          p.join(tempDir.path, 'pubspec.yaml'),
        ).writeAsString(cleanPubspec);
        await File(
          p.join(tempDir.path, 'pubspec.lock'),
        ).writeAsString(cleanLock);
        await File(
          p.join(tempDir.path, 'tool', 'ohos', 'pubspec_ohos.lock'),
        ).writeAsString(ohosLock);

        Future<void> runScript(String flag) async {
          final result = await Process.run('python3', <String>[
            scriptPath,
            '--root',
            tempDir.path,
            flag,
          ]);
          expect(
            result.exitCode,
            0,
            reason: 'apply_ohos_pubspec.py $flag failed: ${result.stderr}',
          );
        }

        // Idempotent --apply (x2)
        await runScript('--apply');
        final appliedOnce = await File(
          p.join(tempDir.path, 'pubspec.yaml'),
        ).readAsString();
        expect(appliedOnce, contains('dependency_overrides:'));
        expect(appliedOnce, contains('path_provider_ohos:'));
        expect(appliedOnce, contains('file_selector_ohos:'));
        expect(appliedOnce, contains('ohos: system'));
        expect(
          await File(p.join(tempDir.path, 'pubspec.lock')).readAsString(),
          ohosLock,
        );

        await runScript('--apply');
        expect(
          await File(p.join(tempDir.path, 'pubspec.yaml')).readAsString(),
          appliedOnce,
        );

        // Idempotent --restore (x2)
        await runScript('--restore');
        expect(
          await File(p.join(tempDir.path, 'pubspec.yaml')).readAsString(),
          cleanPubspec,
        );
        expect(
          await File(p.join(tempDir.path, 'pubspec.lock')).readAsString(),
          cleanLock,
        );
        expect(
          Directory(
            p.join(tempDir.path, '.dart_tool', 'ohos_pubspec_backup'),
          ).existsSync(),
          isFalse,
        );

        await runScript('--restore');
        expect(
          await File(p.join(tempDir.path, 'pubspec.yaml')).readAsString(),
          cleanPubspec,
        );
        expect(
          await File(p.join(tempDir.path, 'pubspec.lock')).readAsString(),
          cleanLock,
        );
      },
    );
  });
}
